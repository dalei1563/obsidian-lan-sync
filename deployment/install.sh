#!/bin/bash
# Compatible with macOS /bin/bash 3.2. No sudo, jq or Python required.
set -eu
printf '%s\n' 'LAN Note Sync 安装助手' '正在检查笔记库和连接信息…'
trap 'printf "%s\n" "安装未完成，请检查上方提示、网络连接和目录权限后重试。" >&2' ERR
if command -v shasum >/dev/null 2>&1; then
  file_hash() { shasum -a 256 "$1" | awk '{print $1}'; }
elif command -v sha256sum >/dev/null 2>&1; then
  file_hash() { sha256sum "$1" | awk '{print $1}'; }
else printf '%s\n' '系统缺少 SHA-256 校验工具，请安装 shasum 或 sha256sum 后重试。' >&2; exit 1; fi
vault=''; connection=''; config_dir='.obsidian'; upgrade=0; connection_action=ask; confirm_switch=0
while [ "$#" -gt 0 ]; do
  case "$1" in
    --vault) vault=$2; shift 2;;
    --connection) connection=$2; shift 2;;
    --config-dir) config_dir=$2; shift 2;;
    --upgrade) upgrade=1; shift;;
    --connection-action) connection_action=$2; shift 2;;
    --confirm-switch) confirm_switch=1; shift;;
    *) printf '%s\n' '命令参数无法识别，请从管理后台重新复制完整命令。' >&2; exit 1;;
  esac
done
if [ -z "$vault" ]; then
  if [ "$(uname -s)" = Darwin ]; then
    vault=$(osascript -e 'POSIX path of (choose folder with prompt "请选择要安装或更新插件的 Obsidian 笔记库")')
  else printf '%s\n' '请通过 --vault 参数指定已有笔记库的完整路径。' >&2; exit 1; fi
fi
case "$connection" in lansync:*) ;; *) printf '%s\n' '连接码不完整，请从管理后台重新复制整条安装命令。' >&2; exit 1;; esac
case "$config_dir" in .*) ;; *) printf '%s\n' 'Obsidian 配置目录无效，请检查目录名称。' >&2; exit 1;; esac
case "${config_dir#.}" in ''|*[!a-zA-Z0-9_-]*) printf '%s\n' 'Obsidian 配置目录无效，请检查目录名称。' >&2; exit 1;; esac
[ -d "$vault/$config_dir" ] || { printf '%s\n' '请先在 Obsidian 中打开这个笔记库，再运行安装命令。' >&2; exit 1; }
vault=$(cd "$vault" && pwd -P)
plugins="$vault/$config_dir/plugins"; target="$plugins/lan-note-sync"
for candidate in "$vault/$config_dir" "$plugins" "$target"; do [ ! -L "$candidate" ] || { printf '%s\n' '不支持通过符号链接安装，请选择笔记库的实际目录。' >&2; exit 1; }; done
if [ -e "$target" ]; then
  if pgrep -x Obsidian >/dev/null 2>&1; then printf '%s\n' '请先完全退出 Obsidian，再重新运行安装命令。' >&2; exit 1; fi
fi
encoded=${connection#lansync:}
[ "${#encoded}" -le 4096 ] || exit 1
padding=$(( (4 - ${#encoded} % 4) % 4 ))
while [ "$padding" -gt 0 ]; do encoded="${encoded}="; padding=$((padding - 1)); done
if [ "$(uname -s)" = Darwin ]; then decode_flag='-D'; else decode_flag='-d'; fi
decoded=$(printf '%s' "$encoded" | tr '_-' '/+' | base64 "$decode_flag")
case "$decoded" in '{"protocol":3,"server":'*) ;; *) printf '%s\n' '连接码版本不兼容，请从管理后台重新生成安装命令。' >&2; exit 1;; esac
# Connection JSON is generated by our encoder. Only the root URL is extracted;
# the plugin validates the complete connection code again before pairing.
server=$(printf '%s' "$decoded" | sed -n 's/.*"server":"\([^"]*\)".*/\1/p')
case "$server" in https://*|http://*) ;; *) printf '%s\n' '连接码中的服务地址无效，请从管理后台重新生成安装命令。' >&2; exit 1;; esac
case "$server" in *[!a-zA-Z0-9:/._\[\]-]*|*@*|*\?*|*\#*) printf '%s\n' '连接码中的服务地址无效，请从管理后台重新生成安装命令。' >&2; exit 1;; esac
# Read saved JSON with the native macOS parser; Linux may use Node or Python.
read_setting() {
  if [ "$(uname -s)" = Darwin ]; then
    /usr/bin/osascript -l JavaScript -e 'ObjC.import("Foundation"); function run(args) { var text = ObjC.unwrap($.NSString.stringWithContentsOfFileEncodingError(args[0], $.NSUTF8StringEncoding, null)); var d = JSON.parse(text.replace(/^\uFEFF/, "")); var v = d[args[1]]; if (v === undefined) return ""; if (typeof v !== "string") throw new Error("配置字段必须是文本"); return v; }' "$target/data.json" "$1"
  elif command -v node >/dev/null 2>&1; then
    node -e 'const fs=require("fs");const d=JSON.parse(fs.readFileSync(process.argv[1],"utf8").replace(/^\uFEFF/,"")); const v=d[process.argv[2]]; if(v!==undefined && typeof v!=="string")process.exit(1);process.stdout.write(v||"")' "$target/data.json" "$1"
  elif command -v python3 >/dev/null 2>&1; then
    python3 -c 'import json,sys; d=json.load(open(sys.argv[1],encoding="utf-8-sig")); v=d.get(sys.argv[2],""); assert isinstance(v,str); print(v,end="")' "$target/data.json" "$1"
  else
    printf '%s\n' '读取已有配置需要系统 JSON 工具。macOS 使用系统 JavaScript 解析器；Linux 请安装 Node.js 或 Python 3。' >&2; return 1
  fi
}
case "$connection_action" in ask|keep|switch) ;; *) printf '%s\n' '连接操作无效，请使用 ask、keep 或 switch。' >&2; exit 1;; esac
bound=0; reconnect=0; old_id=''; old_name=''; old_server=''
if [ -f "$target/data.json" ]; then
  old_id=$(read_setting vaultId) || { printf '%s\n' '原连接配置无法读取，已停止安装，不会自动重置配置。' >&2; exit 1; }
  old_name=$(read_setting vaultName); old_server=$(read_setting server)
  [ -z "$old_id" ] || bound=1
fi
target_id=$(printf '%s' "$decoded" | sed -n 's/.*"vaultId":"\([a-f0-9-]*\)".*/\1/p')
target_label=$(printf '%s' "$decoded" | sed -n 's/.*"vaultLabel":"\([A-Za-z0-9+/=]*\)".*/\1/p')
target_name='未提供仓库名称，请重新生成命令'
if [ -n "$target_label" ]; then target_name=$(printf '%s' "$target_label" | base64 "$decode_flag"); fi
printf '本地笔记库：%s\n本次目标仓库：%s [%s]\n' "$vault" "$target_name" "$target_id"
if [ "$bound" -eq 1 ] && [ "$reconnect" -eq 0 ]; then
  printf '当前连接：%s [%s]\n当前服务：%s\n' "$old_name" "$old_id" "$old_server"
  if [ -n "$target_id" ] && [ "$old_id" = "$target_id" ] && [ "${old_server%/}" = "${server%/}" ] && [ "$connection_action" = ask ]; then
    connection_action=keep
    printf '%s\n' '已连接到本次目标仓库，将仅更新插件。'
  fi
  if [ "$connection_action" = ask ]; then
    printf '%s\n' '检测到已有连接，请选择：' '  1. 仅更新插件，保留原连接（不会连接本次新仓库）' '  2. 切换到本次目标仓库，备份原配置和同步基线' '  0. 取消，不修改任何文件'
    printf '%s' '请输入 1、2 或 0：'
    choice=''
    if ! read -r choice < /dev/tty; then printf '%s\n' '没有可交互的终端，已取消。请在终端中重新运行命令。' >&2; exit 1; fi
    case "$choice" in 1) connection_action=keep;; 2) connection_action=switch;; *) printf '%s\n' '已取消安装，原有文件未修改。'; exit 1;; esac
  fi
  if [ "$connection_action" = switch ]; then
    [ "${#target_id}" -eq 36 ] || { printf '%s\n' '这条旧命令没有目标仓库信息，请从后台重新生成命令后切换。' >&2; exit 1; }
    printf '%s\n' '切换将保留本地笔记，并备份原连接和同步基线。新仓库需要重新配对、预览和确认，不会立即同步。'
    if [ "$confirm_switch" -ne 1 ]; then
      printf '%s' '确认切换请输入：切换：'
      answer=''; read -r answer < /dev/tty || exit 1
      [ "$answer" = '切换' ] || { printf '%s\n' '已取消切换，原有文件未修改。'; exit 1; }
    fi
    reconnect=1
  fi
fi
curl_options=(--fail --silent --show-error --connect-timeout 15 --retry 2)
# Local endpoints must not accidentally be sent through a global HTTP proxy.
case "$server" in http://127.*|https://127.*|http://localhost*|https://localhost*|http://192.168.*|https://192.168.*|http://10.*|https://10.*|http://172.1[6-9].*|https://172.1[6-9].*|http://172.2[0-9].*|https://172.2[0-9].*|http://172.3[01].*|https://172.3[01].*) curl_options+=(--noproxy '*');; esac
server_host=${server#*://}; server_host=${server_host%%:*}
if [[ "$server_host" =~ ^100\.(6[4-9]|[7-9][0-9]|1[01][0-9]|12[0-7])\.[0-9]{1,3}\.[0-9]{1,3}$ ]]; then curl_options+=(--noproxy '*'); fi
mkdir -p "$plugins"
printf '%s\n' '正在获取服务端版本、下载并校验插件文件…'
stage=$(mktemp -d "$plugins/.lan-note-sync-stage-XXXXXXXX")
curl "${curl_options[@]}" --max-time 30 "$server/install/manifest" -o "$stage/plan.json" 2>/dev/null || { printf "%s\n" "无法获取服务端插件信息，请检查网络和服务地址后重试。" >&2; exit 1; }
# The server publishes a compact, strictly shaped install plan. Avoid depending
# on a JSON command-line parser on stock macOS.
for name in manifest.json main.js styles.css; do
  expected=$(tr -d '\n\r' < "$stage/plan.json" | sed -n 's/.*{"name":"'"$name"'","sha256":"\([a-f0-9]*\)","size":[0-9]*}.*/\1/p')
  [ "${#expected}" -eq 64 ] || { printf '%s\n' '服务端安装清单无效，请联系管理员检查发布文件。' >&2; exit 1; }
  curl "${curl_options[@]}" --max-time 60 "$server/install/files/$name" -o "$stage/$name" 2>/dev/null || { printf "插件文件下载失败：%s。请检查网络后重试，原有安装未修改。\n" "$name" >&2; exit 1; }
  actual=$(file_hash "$stage/$name")
  [ "$actual" = "$expected" ] || { printf '%s\n' '插件下载校验失败，原有安装未修改，请检查网络后重试。' >&2; exit 1; }
done
grep -Eq '"id"[[:space:]]*:[[:space:]]*"lan-note-sync"' "$stage/manifest.json" || exit 1
if [ -e "$target" ]; then
  if [ "$reconnect" -eq 0 ]; then
    shopt -s dotglob nullglob
    for item in "$target"/*; do
      case "${item##*/}" in manifest.json|main.js|styles.css|plan.json) ;; *) cp -R "$item" "$stage/";; esac
    done
    shopt -u dotglob nullglob
  fi
  if [ "$bound" -eq 0 ] || [ "$reconnect" -eq 1 ]; then
    umask 077
    printf '{"schema":1,"connection":"%s"}\n' "$connection" > "$stage/bootstrap.json"
  fi
  if [ "$reconnect" -eq 1 ]; then printf '%s\n' '{"enabled":false}' > "$stage/data.json"; fi
  backup_root="$vault/$config_dir/lan-note-sync-backups"
  [ ! -L "$backup_root" ] || { printf '%s\n' '备份目录不能是符号链接，请使用实际目录。' >&2; exit 1; }
  mkdir -p "$backup_root"
  backup="$backup_root/lan-note-sync-$(date +%Y%m%d%H%M%S)-$$"
  case "$target" in "$plugins/lan-note-sync") ;; *) exit 1;; esac
  mv "$target" "$backup"
  if ! mv "$stage" "$target"; then mv "$backup" "$target"; exit 1; fi
  printf '原版本已备份至：%s\n' "$backup"
else
  umask 077
  printf '{"schema":1,"connection":"%s"}\n' "$connection" > "$stage/bootstrap.json"
  mv "$stage" "$target"
fi
printf '\n%s\n' '安装完成：LAN Note Sync'
printf '笔记库位置：%s\n' "$vault"
if [ "$bound" -eq 1 ] && [ "$reconnect" -eq 0 ]; then
  printf '%s\n' '仅更新完成，原有配置和同步状态已保留。本次命令的新连接码未使用。'
else
  if [ "$reconnect" -eq 1 ]; then printf '%s\n' '已准备切换仓库，原连接与同步基线已备份。'; fi
  printf '%s\n' '连接配置已写入，尚未完成设备连接。接下来：' '  1. 打开上述笔记库，进入「设置 → 第三方插件」。' '  2. 启用 LAN Note Sync，按提示完成连接。' '  3. 检查并确认首次同步预览，再开始同步。' '首次连接请在邀请有效期内完成；若已过期，请重新生成命令。'
fi
printf '%s\n' '笔记内容和其他插件未修改。现在可以关闭此窗口。'
