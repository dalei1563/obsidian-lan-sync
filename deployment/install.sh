#!/bin/bash
# Compatible with macOS /bin/bash 3.2. No sudo, jq or Python required.
set -eu
if command -v shasum >/dev/null 2>&1; then
  file_hash() { shasum -a 256 "$1" | awk '{print $1}'; }
elif command -v sha256sum >/dev/null 2>&1; then
  file_hash() { sha256sum "$1" | awk '{print $1}'; }
else printf '%s\n' 'SHA-256 tool is unavailable.' >&2; exit 1; fi
vault=''; connection=''; config_dir='.obsidian'; upgrade=0
while [ "$#" -gt 0 ]; do
  case "$1" in
    --vault) vault=$2; shift 2;;
    --connection) connection=$2; shift 2;;
    --config-dir) config_dir=$2; shift 2;;
    --upgrade) upgrade=1; shift;;
    *) printf '%s\n' 'Unknown argument.' >&2; exit 1;;
  esac
done
if [ -z "$vault" ]; then
  if [ "$(uname -s)" = Darwin ]; then
    vault=$(osascript -e 'POSIX path of (choose folder with prompt "Choose the Obsidian Vault to connect")')
  else printf '%s\n' 'Specify the existing Vault with --vault /path/to/vault.' >&2; exit 1; fi
fi
case "$connection" in lansync:*) ;; *) printf '%s\n' 'Use the full connection code from your administrator.' >&2; exit 1;; esac
case "$config_dir" in .*) ;; *) printf '%s\n' 'Invalid configuration directory.' >&2; exit 1;; esac
case "${config_dir#.}" in ''|*[!a-zA-Z0-9_-]*) printf '%s\n' 'Invalid configuration directory.' >&2; exit 1;; esac
[ -d "$vault/$config_dir" ] || { printf '%s\n' 'Open this folder as a Vault in Obsidian first.' >&2; exit 1; }
vault=$(cd "$vault" && pwd -P)
plugins="$vault/$config_dir/plugins"; target="$plugins/lan-note-sync"
for candidate in "$vault/$config_dir" "$plugins" "$target"; do [ ! -L "$candidate" ] || { printf '%s\n' 'Symbolic link installation is not supported.' >&2; exit 1; }; done
if [ -e "$target" ]; then
  [ "$upgrade" -eq 1 ] || { printf '%s\n' 'Already installed. Close Obsidian and use --upgrade; connection and state will be preserved.' >&2; exit 1; }
  if pgrep -x Obsidian >/dev/null 2>&1; then printf '%s\n' 'Close Obsidian before upgrading.' >&2; exit 1; fi
fi
encoded=${connection#lansync:}
[ "${#encoded}" -le 4096 ] || exit 1
padding=$(( (4 - ${#encoded} % 4) % 4 ))
while [ "$padding" -gt 0 ]; do encoded="${encoded}="; padding=$((padding - 1)); done
if [ "$(uname -s)" = Darwin ]; then decode_flag='-D'; else decode_flag='-d'; fi
decoded=$(printf '%s' "$encoded" | tr '_-' '/+' | base64 "$decode_flag")
case "$decoded" in '{"protocol":2,"server":'*) ;; *) printf '%s\n' 'Connection version is incompatible. Request a fresh invite.' >&2; exit 1;; esac
# Connection JSON is generated by our encoder. Only the root URL is extracted;
# the plugin validates the complete connection code again before pairing.
server=$(printf '%s' "$decoded" | sed -n 's/.*"server":"\([^"]*\)".*/\1/p')
case "$server" in https://*|http://*) ;; *) printf '%s\n' 'Invalid server URL.' >&2; exit 1;; esac
case "$server" in *[!a-zA-Z0-9:/._\[\]-]*|*@*|*\?*|*\#*) printf '%s\n' 'Invalid server URL.' >&2; exit 1;; esac
curl_options=(--fail --silent --show-error --connect-timeout 15 --retry 2)
# Local endpoints must not accidentally be sent through a global HTTP proxy.
case "$server" in http://127.*|https://127.*|http://localhost*|https://localhost*|http://192.168.*|https://192.168.*|http://10.*|https://10.*|http://172.1[6-9].*|https://172.1[6-9].*|http://172.2[0-9].*|https://172.2[0-9].*|http://172.3[01].*|https://172.3[01].*) curl_options+=(--noproxy '*');; esac
server_host=${server#*://}; server_host=${server_host%%:*}
if [[ "$server_host" =~ ^100\.(6[4-9]|[7-9][0-9]|1[01][0-9]|12[0-7])\.[0-9]{1,3}\.[0-9]{1,3}$ ]]; then curl_options+=(--noproxy '*'); fi
mkdir -p "$plugins"
stage=$(mktemp -d "$plugins/.lan-note-sync-stage-XXXXXXXX")
curl "${curl_options[@]}" --max-time 30 "$server/install/manifest" -o "$stage/plan.json"
# The server publishes a compact, strictly shaped install plan. Avoid depending
# on a JSON command-line parser on stock macOS.
for name in manifest.json main.js styles.css; do
  expected=$(tr -d '\n\r' < "$stage/plan.json" | sed -n 's/.*{"name":"'"$name"'","sha256":"\([a-f0-9]*\)","size":[0-9]*}.*/\1/p')
  [ "${#expected}" -eq 64 ] || { printf '%s\n' 'Invalid install manifest.' >&2; exit 1; }
  curl "${curl_options[@]}" --max-time 60 "$server/install/files/$name" -o "$stage/$name"
  actual=$(file_hash "$stage/$name")
  [ "$actual" = "$expected" ] || { printf '%s\n' 'Download integrity check failed. Existing installation was not changed.' >&2; exit 1; }
done
grep -Eq '"id"[[:space:]]*:[[:space:]]*"lan-note-sync"' "$stage/manifest.json" || exit 1
if [ -e "$target" ]; then
  # Copy state into the staging directory; never remove the old directory.
  shopt -s dotglob nullglob
  for item in "$target"/*; do
    case "${item##*/}" in manifest.json|main.js|styles.css|plan.json) ;; *) cp -R "$item" "$stage/";; esac
  done
  shopt -u dotglob nullglob
  backup="$target.backup-$(date +%Y%m%d%H%M%S)-$$"
  case "$target" in "$plugins/lan-note-sync") ;; *) exit 1;; esac
  mv "$target" "$backup"
  if ! mv "$stage" "$target"; then mv "$backup" "$target"; exit 1; fi
  printf 'Previous installation retained: %s\n' "$backup"
else
  umask 077
  printf '{"schema":1,"connection":"%s"}\n' "$connection" > "$stage/bootstrap.json"
  mv "$stage" "$target"
fi
printf '%s\n' 'Installed LAN Note Sync. Open this Vault in Obsidian, enable the plugin, and confirm the initial sync preview.'
